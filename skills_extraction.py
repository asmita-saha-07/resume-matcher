def extract_skills(text):
    text=text.lower()
    found=[]
    for category, skills in skill_dictionary.items():
      for skill, aliases in skills.items():
        for alias in aliases:
            pattern = r"(?<!\w)" + re.escape(alias) + r"(?!\w)"
            if re.search(pattern, text):
                found.append(skill)
                break
    return found



